import type { Metadata } from 'next';
import { JetBrains_Mono } from 'next/font/google';
import { Suspense } from 'react';

import { IframePathSync } from '@/components/nav/iframe-path-sync';
import { TopNav } from '@/components/nav/top-nav';
import { ThemeProvider } from '@/components/theme-provider';

import './globals.css';

// JetBrains Mono - the Datum Labs terminal face, matching the Lending
// Intelligence Terminal at datumlab.xyz/lending-terminal. Used for all text
// (prose, labels, and numeric cells) via the --font-jetbrains CSS variable.
const jetbrainsMono = JetBrains_Mono({
  subsets: ['latin'],
  display: 'swap',
  variable: '--font-jetbrains',
});

// Pre-paint theme script. Reads the persisted choice from localStorage and
// writes `data-theme` to <html> before React hydrates. Without this inline
// pass, a user with light-mode persisted would see a dark-mode flash on
// every page load. Next.js's <Script> loads AFTER paint, so we inline.
const THEME_INIT_SCRIPT = `
(function () {
  try {
    var saved = window.localStorage.getItem('morpho-theme');
    if (saved !== 'light' && saved !== 'dark') saved = 'dark';
    document.documentElement.setAttribute('data-theme', saved);
  } catch (e) {
    document.documentElement.setAttribute('data-theme', 'dark');
  }
})();
`;

// Pre-paint iframe path restore. When embedded at datumlab.xyz/morpho-terminal,
// the parent reloads the iframe at "/" on refresh. This runs synchronously in
// <head> before Overview paints: if a different path was stored on the last
// route change (see IframePathSync), it location.replaces straight to it, so
// the user never sees an Overview flash. Inert in the top window (standalone),
// where native routing already lands on the right page.
const IFRAME_RESTORE_SCRIPT = `
(function () {
  try {
    if (window.parent === window) return;
    var stored = window.sessionStorage.getItem('morpho-terminal-path');
    if (!stored || stored.charAt(0) !== '/') return;
    var current = window.location.pathname + window.location.search;
    if (stored !== current) window.location.replace(stored);
  } catch (e) {}
})();
`;

const SITE_URL =
  process.env.NEXT_PUBLIC_SITE_URL ?? 'https://datumlab.xyz';

const DESCRIPTION =
  'Research-grade dashboard tracking Morpho across 12 chains, 26 curators, 1000+ markets. Active loans, curator economics, asset composition, lending sector position.';

// The social card is the static public/og.png (generated by
// scripts/gen-brand-assets.ts). Favicons come from the app/icon.png,
// app/apple-icon.png and app/favicon.ico file conventions.
export const metadata: Metadata = {
  title: 'Morpho Research Terminal · Datum Labs',
  description: DESCRIPTION,
  metadataBase: new URL(SITE_URL),
  openGraph: {
    siteName: 'DatumLabs Research',
    title: 'Morpho Research Terminal · Datum Labs',
    description: DESCRIPTION,
    url: SITE_URL,
    type: 'website',
    images: [{ url: '/og.png', width: 1200, height: 630, alt: 'Morpho Research Terminal' }],
  },
  twitter: {
    card: 'summary_large_image',
    site: '@datumlabs',
    creator: '@datumlabs',
    title: 'Morpho Research Terminal · Datum Labs',
    description: DESCRIPTION,
    images: ['/og.png'],
  },
};

export default function RootLayout({ children }: { children: React.ReactNode }) {
  return (
    <html lang="en" data-theme="dark" suppressHydrationWarning className={jetbrainsMono.variable}>
      <head>
        <script dangerouslySetInnerHTML={{ __html: THEME_INIT_SCRIPT }} />
        <script dangerouslySetInnerHTML={{ __html: IFRAME_RESTORE_SCRIPT }} />
      </head>
      <body className="min-h-screen bg-background text-text-primary font-sans antialiased">
        <ThemeProvider>
          <Suspense fallback={null}>
            <IframePathSync />
          </Suspense>
          <TopNav />
          {/* Standard page wrapper from globals.css. Caps at 1400px so dense
              chart grids stay legible on ultra-wide displays. */}
          <main className="max-w-[1400px] mx-auto px-4 lg:px-6 py-5 space-y-5">
            {children}
          </main>
        </ThemeProvider>
      </body>
    </html>
  );
}
